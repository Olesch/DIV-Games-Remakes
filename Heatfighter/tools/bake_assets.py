"""Bakes (1) the palette-swapped 'player 2' PNGs (DIV convert_palette: index -> (index+16) mod 256
for graphs 1..100) and (2) scripts/gfx_data.gd (sizes + control point 0 of every graphic).
Run from the project folder after div_convert.py:  python tools/bake_assets.py"""
import json, os, struct, zlib

def write_png(path, w, h, rgba):
    raw = b"".join(b"\x00" + rgba[y*w*4:(y+1)*w*4] for y in range(h))
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))

lines = ["# GENERATED by tools/bake_assets.py - do not edit.",
         "# name -> { graphic code -> [width, height, cp0_x, cp0_y] }  (cp0 = DIV origin of the graphic)",
         "class_name GfxData", "extends RefCounted", "", "const DATA := {"]
for name in ("heatfigh", "hftemp", "hfchain", "hfeigen"):
    d = f"assets/fpg/{name}"
    meta = json.load(open(d + "/meta.json"))
    pal = meta["palette_rgb8"]
    idx = open(d + "/indices.bin", "rb").read()
    out = f"assets/fpg/{name}_p2"
    os.makedirs(out, exist_ok=True)
    lines.append(f'\t"{name}": {{')
    for g in meta["graphics"]:
        code, w, h = g["code"], g["width"], g["height"]
        lines.append(f'\t\t{code}: [{w}, {h}, {g["cp0"][0]}, {g["cp0"][1]}],')
        if name == "heatfigh":
            continue
        data = idx[g["offset"]:g["offset"] + w*h]
        buf = bytearray(w*h*4)
        for i, v in enumerate(data):
            if code <= 100 and v:
                v = (v + 16) % 256
            if v:
                r, gg, b = pal[v]
                buf[i*4:i*4+4] = bytes((r, gg, b, 255))
        write_png(f"{out}/{code}.png", w, h, bytes(buf))
    lines.append("\t},")
lines.append("}")
open("scripts/gfx_data.gd", "w").write("\n".join(lines) + "\n")
print("ok")
